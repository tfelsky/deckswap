-- Internal: close an open slot for shipping. Charges one combined shipment for
-- every queued order in it and moves those orders to awaiting_shipment. Callers
-- authorize first; a slot that is already settled is returned unchanged.
create or replace function public.settle_singles_mail_slot(p_slot_id bigint, p_reason text)
returns public.singles_mail_slots
language plpgsql
security definer
set search_path = public
as $$
declare
  v_slot public.singles_mail_slots;
  v_subtotal numeric := 0;
  v_item_count integer := 0;
  v_shipping_method text;
  v_shipping_amount numeric;
begin
  select * into v_slot from public.singles_mail_slots where id = p_slot_id for update;

  if not found then
    raise exception 'Mail slot not found.';
  end if;

  if v_slot.status <> 'open' then
    return v_slot;
  end if;

  select coalesce(sum(item_subtotal_usd), 0), coalesce(sum(item_count), 0)::integer
  into v_subtotal, v_item_count
  from public.singles_orders
  where mail_slot_id = p_slot_id
    and status = 'queued';

  -- One shipment for the whole slot, on create_singles_checkout's thresholds.
  if v_subtotal > 30 or v_item_count > 10 then
    v_shipping_method := 'tracked_padded_mailer';
    v_shipping_amount := 15;
  else
    v_shipping_method := 'pwe_untracked';
    v_shipping_amount := 5;
  end if;

  update public.singles_mail_slots
  set
    status = 'ready_to_ship',
    release_reason = p_reason,
    released_at = now(),
    shipping_method = v_shipping_method,
    shipping_amount_usd = v_shipping_amount,
    updated_at = now()
  where id = p_slot_id
  returning * into v_slot;

  insert into public.singles_mail_slot_charges (mail_slot_id, kind, amount_usd)
  values (p_slot_id, 'shipping', v_shipping_amount);

  update public.singles_orders
  set status = 'awaiting_shipment', updated_at = now()
  where mail_slot_id = p_slot_id
    and status = 'queued';

  return v_slot;
end;
$$;

revoke execute on function public.settle_singles_mail_slot(bigint, text) from public, anon, authenticated;

-- Buyer: ship my slot now. Service role (the daily cron): settle a lapsed hold.
create or replace function public.release_singles_mail_slot(p_slot_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_slot public.singles_mail_slots;
begin
  select * into v_slot from public.singles_mail_slots where id = p_slot_id for update;

  if not found then
    raise exception 'Mail slot not found.';
  end if;

  if v_slot.status <> 'open' then
    raise exception 'This mail slot has already been released.';
  end if;

  if coalesce(auth.jwt() ->> 'role', '') = 'service_role' then
    if v_slot.held_until > now() then
      raise exception 'This mail slot is still on hold.';
    end if;

    select * into v_slot from public.settle_singles_mail_slot(p_slot_id, 'hold_expired');
  elsif auth.uid() = v_slot.buyer_user_id then
    select * into v_slot from public.settle_singles_mail_slot(
      p_slot_id,
      case when v_slot.held_until > now() then 'buyer_request' else 'hold_expired' end
    );
  else
    raise exception 'Only the buyer can release this mail slot.';
  end if;

  return jsonb_build_object('mailSlot', to_jsonb(v_slot));
end;
$$;

revoke execute on function public.release_singles_mail_slot(bigint) from public, anon;
grant execute on function public.release_singles_mail_slot(bigint) to authenticated, service_role;

-- Buyer: pay more rent to keep an open slot holding, up to its 13-week cap.
create or replace function public.extend_singles_mail_slot(p_slot_id bigint, p_weeks integer)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_rent_per_week_usd constant numeric := 1;
  v_slot public.singles_mail_slots;
  v_weeks integer := coalesce(p_weeks, 0);
  v_remaining_weeks integer;
  v_rent numeric;
begin
  select * into v_slot from public.singles_mail_slots where id = p_slot_id for update;

  if not found then
    raise exception 'Mail slot not found.';
  end if;

  if auth.uid() is distinct from v_slot.buyer_user_id then
    raise exception 'Only the buyer can extend this mail slot.';
  end if;

  if v_slot.status <> 'open' then
    raise exception 'This mail slot has already been released for shipping.';
  end if;

  if v_weeks < 1 then
    raise exception 'Choose at least one week to extend the hold.';
  end if;

  v_remaining_weeks := public.singles_mail_slot_remaining_weeks(v_slot.held_until, v_slot.max_hold_until);
  if v_weeks > v_remaining_weeks then
    raise exception 'This mail slot can only be extended % more week(s); slots max out 13 weeks after opening.', v_remaining_weeks;
  end if;

  v_rent := round(v_weeks * v_rent_per_week_usd, 2);

  update public.singles_mail_slots
  set
    held_until = greatest(held_until, now()) + make_interval(weeks => v_weeks),
    weeks_purchased = weeks_purchased + v_weeks,
    rent_paid_usd = rent_paid_usd + v_rent,
    updated_at = now()
  where id = p_slot_id
  returning * into v_slot;

  insert into public.singles_mail_slot_charges (mail_slot_id, kind, weeks, amount_usd)
  values (p_slot_id, 'rent', v_weeks, v_rent);

  return jsonb_build_object('mailSlot', to_jsonb(v_slot), 'rentUsd', v_rent);
end;
$$;

