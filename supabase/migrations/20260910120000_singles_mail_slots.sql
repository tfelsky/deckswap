-- Queue My Order: singles mail slots.
--
-- A buyer can pay for singles now and have the seller hold them instead of
-- shipping. Held orders sit in a "mail slot" — one open slot per buyer + seller —
-- and every later queued order from that seller drops into the same slot. The
-- whole slot ships once, with one combined shipping charge, when the buyer
-- releases it or the paid-up hold runs out (/api/cron/release-mail-slots settles
-- lapsed holds daily; the seller can also ship a lapsed slot directly).
--
-- The buyer rents the slot from the seller in whole weeks: $1/week, capped at 13
-- weeks from opening so the shipment lands well inside the ~120-day card-network
-- chargeback window. lib/singles/mail-slots.ts mirrors these numbers for quotes;
-- this file is the source of truth. Every state change runs through the
-- security-definer functions below — the new tables only carry read policies.
--
-- Idempotent: create-if-not-exists / drop-if-exists guards make it safe to re-run.

create table if not exists public.singles_mail_slots (
  id bigint generated by default as identity primary key,
  buyer_user_id uuid not null references auth.users(id) on delete cascade,
  seller_user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'open',
  opened_at timestamptz not null default now(),
  held_until timestamptz not null,
  max_hold_until timestamptz not null,
  weeks_purchased integer not null default 0,
  rent_paid_usd numeric not null default 0,
  release_reason text,
  released_at timestamptz,
  shipping_method text,
  shipping_amount_usd numeric,
  tracking_code text,
  shipped_at timestamptz,
  delivered_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (status in ('open', 'ready_to_ship', 'shipped', 'delivered')),
  check (release_reason is null or release_reason in ('buyer_request', 'hold_expired')),
  check (held_until <= max_hold_until)
);

-- Queued orders from the same seller always land in the same slot.
create unique index if not exists singles_mail_slots_one_open_per_pair
  on public.singles_mail_slots (buyer_user_id, seller_user_id)
  where status = 'open';

create index if not exists singles_mail_slots_buyer_idx
  on public.singles_mail_slots (buyer_user_id, created_at desc);

create index if not exists singles_mail_slots_seller_idx
  on public.singles_mail_slots (seller_user_id, created_at desc);

create index if not exists singles_mail_slots_lapsed_idx
  on public.singles_mail_slots (status, held_until);

-- Ledger of everything a slot has cost the buyer: rent (at checkout or on
-- extension) and the one combined shipping charge when it is released.
create table if not exists public.singles_mail_slot_charges (
  id bigint generated by default as identity primary key,
  mail_slot_id bigint not null references public.singles_mail_slots(id) on delete cascade,
  order_id bigint references public.singles_orders(id) on delete set null,
  kind text not null,
  weeks integer not null default 0,
  amount_usd numeric not null default 0,
  created_at timestamptz not null default now(),
  check (kind in ('rent', 'shipping'))
);

create index if not exists singles_mail_slot_charges_slot_idx
  on public.singles_mail_slot_charges (mail_slot_id, created_at asc);

alter table public.singles_orders
  add column if not exists mail_slot_id bigint references public.singles_mail_slots(id) on delete set null,
  add column if not exists slot_rent_usd numeric not null default 0;

create index if not exists singles_orders_mail_slot_idx
  on public.singles_orders (mail_slot_id)
  where mail_slot_id is not null;

-- Add 'queued' to the order lifecycle. The original status check was unnamed,
-- so find it by definition rather than trusting the generated name.
do $$
declare
  v_constraint_name text;
begin
  for v_constraint_name in
    select conname
    from pg_constraint
    where conrelid = 'public.singles_orders'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) like '%awaiting_shipment%'
  loop
    execute format('alter table public.singles_orders drop constraint %I', v_constraint_name);
  end loop;
end
$$;

