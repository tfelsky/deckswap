-- Seller: ship everything in the slot as one package. Allowed once the buyer has
-- released it or the paid hold has lapsed — never while the buyer is paying to hold.
create or replace function public.ship_singles_mail_slot(p_slot_id bigint, p_tracking_code text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_slot public.singles_mail_slots;
  v_tracking_code text := nullif(trim(coalesce(p_tracking_code, '')), '');
begin
  select * into v_slot from public.singles_mail_slots where id = p_slot_id for update;

  if not found then
    raise exception 'Mail slot not found.';
  end if;

  if auth.uid() is distinct from v_slot.seller_user_id then
    raise exception 'Only the seller can ship this mail slot.';
  end if;

  if v_slot.status = 'open' then
    if v_slot.held_until > now() then
      raise exception 'The buyer paid to hold this slot until %. Ship it once they release it or the hold ends.',
        to_char(v_slot.held_until, 'Mon DD, YYYY');
    end if;

    select * into v_slot from public.settle_singles_mail_slot(p_slot_id, 'hold_expired');
  end if;

  if v_slot.status <> 'ready_to_ship' then
    raise exception 'This mail slot has already shipped.';
  end if;

  update public.singles_mail_slots
  set
    status = 'shipped',
    tracking_code = v_tracking_code,
    shipped_at = now(),
    updated_at = now()
  where id = p_slot_id
  returning * into v_slot;

  update public.singles_orders
  set
    status = 'shipped',
    tracking_code = v_tracking_code,
    shipped_at = now(),
    updated_at = now()
  where mail_slot_id = p_slot_id
    and status = 'awaiting_shipment';

  return jsonb_build_object('mailSlot', to_jsonb(v_slot));
end;
$$;

revoke execute on function public.ship_singles_mail_slot(bigint, text) from public, anon;
grant execute on function public.ship_singles_mail_slot(bigint, text) to authenticated;

-- Buyer: the package arrived. Completes every order in the slot in one step and
-- returns their ids so the app can mint reward points per order.
create or replace function public.confirm_singles_mail_slot_delivered(p_slot_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_slot public.singles_mail_slots;
  v_order_ids jsonb;
begin
  select * into v_slot from public.singles_mail_slots where id = p_slot_id for update;

  if not found then
    raise exception 'Mail slot not found.';
  end if;

  if auth.uid() is distinct from v_slot.buyer_user_id then
    raise exception 'Only the buyer can confirm delivery.';
  end if;

  if v_slot.status <> 'shipped' then
    raise exception 'This mail slot is not out for delivery.';
  end if;

  with completed as (
    update public.singles_orders
    set
      status = 'completed',
      delivered_at = now(),
      completed_at = now(),
      updated_at = now()
    where mail_slot_id = p_slot_id
      and status = 'shipped'
    returning id
  )
  select coalesce(jsonb_agg(id order by id), '[]'::jsonb) into v_order_ids from completed;

  update public.singles_mail_slots
  set status = 'delivered', delivered_at = now(), updated_at = now()
  where id = p_slot_id
  returning * into v_slot;

  return jsonb_build_object('mailSlot', to_jsonb(v_slot), 'orderIds', v_order_ids);
end;
$$;

revoke execute on function public.confirm_singles_mail_slot_delivered(bigint) from public, anon;
grant execute on function public.confirm_singles_mail_slot_delivered(bigint) to authenticated;
