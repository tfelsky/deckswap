create table if not exists public.qship_boxes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  cycle_month date not null,
  status text not null default 'drafting',
  plan_key text not null,
  box_value_usd numeric not null,
  market_value_at_pick_usd numeric,
  cost_basis_usd numeric,
  fee_usd numeric,
  shipping_level text,
  shipping_usd numeric not null default 0,
  credit_applied_usd numeric not null default 0,
  charged_usd numeric,
  theme_title text,
  theme_story text,
  bundles_considered jsonb not null default '[]'::jsonb,
  model text,
  prompt_version text,
  review_deadline timestamptz,
  approved_at timestamptz,
  auto_approved boolean not null default false,
  stripe_payment_intent_id text,
  shipment_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, cycle_month),
  check (status in (
    'drafting', 'preview', 'approved', 'skipped', 'charged',
    'vaulted', 'shipped', 'delivered', 'cancelled'
  )),
  check (plan_key in ('starter', 'standard', 'collector')),
  check (shipping_level is null or shipping_level in ('pwe_untracked', 'tracked_padded_mailer', 'tracked_insured'))
);

create index if not exists qship_boxes_status_idx
  on public.qship_boxes (status, review_deadline);

