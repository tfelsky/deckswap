-- QShip: AI-curated monthly singles subscription (docs/ai-trader-spec.md).
-- Subscriptions and preferences, per-printing price history, market signals,
-- hub inventory (house pool + QShip Supply inbound), boxes and their items,
-- cached card stories, sell signals, shipments, and an audit log.
-- Idempotent: create-if-not-exists / add-column-if-not-exists / drop-policy-
-- if-exists guards make it safe to re-run.

create table if not exists public.qship_subscriptions (
  user_id uuid primary key references auth.users(id) on delete cascade,
  plan_key text not null default 'standard',
  status text not null default 'active',
  billing_interval text not null default 'monthly',
  box_value_usd numeric not null,
  fee_rate numeric not null,
  currency text not null default 'USD',
  stripe_customer_id text,
  stripe_payment_method_id text,
  fulfillment_mode text not null default 'vault_quarterly',
  shipping_level text not null default 'tracked_padded_mailer',
  risk_profile text not null default 'balanced',
  auto_approve boolean not null default true,
  auto_approve_consented_at timestamptz,
  review_window_hours integer not null default 72,
  cycle_anchor_day integer not null default 1,
  box_credit_usd numeric not null default 0,
  prepaid_boxes_remaining integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (plan_key in ('starter', 'standard', 'collector')),
  check (status in ('active', 'paused', 'past_due', 'cancelled')),
  check (billing_interval in ('monthly', 'annual')),
  check (fulfillment_mode in ('vault_quarterly', 'ship_monthly')),
  check (shipping_level in ('pwe_untracked', 'tracked_padded_mailer', 'tracked_insured')),
  check (risk_profile in ('player', 'balanced', 'speculator')),
  check (fee_rate >= 0 and fee_rate <= 0.07),
  check (review_window_hours between 24 and 168),
  check (cycle_anchor_day between 1 and 28),
  check (box_credit_usd >= 0),
  check (prepaid_boxes_remaining >= 0)
);

create table if not exists public.qship_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  focus_deck_ids bigint[] not null default '{}'::bigint[],
  finish_pref text not null default 'any',
  frame_prefs text[] not null default '{}'::text[],
  favorite_artists text[] not null default '{}'::text[],
  lore_interests text[] not null default '{}'::text[],
  blocked_oracle_ids text[] not null default '{}'::text[],
  blocked_set_codes text[] not null default '{}'::text[],
  blocked_artists text[] not null default '{}'::text[],
  min_condition text not null default 'light_play',
  language text not null default 'en',
  goals text,
  goal_tags text[] not null default '{}'::text[],
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (finish_pref in ('nonfoil', 'foil', 'etched', 'any')),
  check (min_condition in ('damaged', 'heavy_play', 'moderate_play', 'light_play', 'near_mint'))
);

-- Daily price per printing. Written by the price cron with the service role.
create table if not exists public.card_price_snapshots (
  scryfall_id text not null,
  captured_on date not null,
  usd numeric,
  usd_foil numeric,
  usd_etched numeric,
  eur numeric,
  buylist_usd numeric,
  buylist_source text,
  source text not null default 'scryfall',
  created_at timestamptz not null default now(),
  primary key (scryfall_id, captured_on)
);

create index if not exists card_price_snapshots_captured_idx
  on public.card_price_snapshots (captured_on desc);

create table if not exists public.market_signals (
  id bigint generated by default as identity primary key,
  scryfall_id text,
  oracle_id text,
  kind text not null,
  strength numeric not null default 0,
  detail text not null,
  source_url text,
  detected_at timestamptz not null default now(),
  expires_at timestamptz,
  check (kind in ('momentum', 'reprint_risk', 'new_synergy', 'meta_rise', 'rotation', 'spike')),
  check (scryfall_id is not null or oracle_id is not null)
);

create index if not exists market_signals_oracle_idx
  on public.market_signals (oracle_id, kind);

create index if not exists market_signals_scryfall_idx
  on public.market_signals (scryfall_id, kind);

-- Everything that is, or will be, at the hub: house pool stock plus QShip
-- Supply copies on their way in. owner_user_id is set once a box allocates it.
create table if not exists public.qship_inventory (
  id bigint generated by default as identity primary key,
  scryfall_id text not null,
  oracle_id text not null,
  card_name text not null,
  set_code text,
  set_name text,
  collector_number text,
  image_url text,
  condition text not null default 'near_mint',
  foil boolean not null default false,
  finish text not null default 'nonfoil',
  language text not null default 'en',
  acquisition_cost_usd numeric not null,
  acquisition_channel text not null,
  source_single_inventory_item_id bigint references public.single_inventory_items(id) on delete set null,
  source_singles_order_id bigint references public.singles_orders(id) on delete set null,
  status text not null default 'receiving',
  owner_user_id uuid references auth.users(id) on delete set null,
  reserved_for_box_id bigint,
  bin_location text,
  intake_photo_url text,
  expected_by date,
  received_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (condition in ('damaged', 'heavy_play', 'moderate_play', 'light_play', 'near_mint')),
  check (finish in ('nonfoil', 'foil', 'etched')),
  check (acquisition_channel in ('trade_in', 'arber_ebay', 'trade_network', 'supply', 'wholesale')),
  check (status in (
    'inbound', 'receiving', 'available', 'reserved', 'vaulted',
    'ship_requested', 'shipped', 'traded_in', 'sold', 'failed'
  )),
  check (acquisition_cost_usd >= 0)
);

create index if not exists qship_inventory_status_idx
  on public.qship_inventory (status, oracle_id);

create index if not exists qship_inventory_owner_idx
  on public.qship_inventory (owner_user_id, status);

alter table public.single_inventory_items
