create table if not exists public.qship_sell_signals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  source_kind text not null,
  source_id text not null,
  card_name text not null,
  oracle_id text,
  kind text not null,
  headline text not null,
  detail text,
  market_price_usd numeric,
  trade_in_cash_usd numeric,
  trade_in_credit_usd numeric,
  suggested_action text not null,
  status text not null default 'open',
  detected_at timestamptz not null default now(),
  expires_at timestamptz,
  updated_at timestamptz not null default now(),
  check (source_kind in ('single_inventory', 'deck_card', 'vault')),
  check (kind in ('reprint_incoming', 'peak', 'buylist_spike', 'dead_weight', 'better_printing')),
  check (suggested_action in ('sell_before_release', 'list_or_trade_in', 'trade_in', 'trade_up')),
  check (status in ('open', 'dismissed', 'listed', 'traded_in', 'expired'))
);

create index if not exists qship_sell_signals_user_idx
  on public.qship_sell_signals (user_id, status, detected_at desc);

create table if not exists public.qship_shipments (
  id bigint generated by default as identity primary key,
